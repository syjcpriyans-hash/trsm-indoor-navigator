import { chromium } from "@playwright/test";
const [,, base, prefix, w, h] = process.argv;
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const mobile = +w < 800;
const page = await browser.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: 2, hasTouch: mobile, isMobile: mobile });
const errs = [];
page.on("pageerror", (e) => errs.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await page.goto(base, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${prefix}-0-home.png` });
await page.getByTestId("search").first().click();
await page.getByTestId("search").first().fill("2-148");
await page.waitForTimeout(400);
await page.screenshot({ path: `${prefix}-1-search.png` });
await page.getByTestId("search-result").first().click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${prefix}-2-place.png` });
await page.getByTestId("directions").click();
await page.waitForTimeout(1800);
await page.screenshot({ path: `${prefix}-3-directions.png` });
await page.getByTestId("demo-walk").click();
await page.waitForTimeout(3500);
await page.screenshot({ path: `${prefix}-4-demo.png` });
await page.waitForTimeout(9000);
await page.screenshot({ path: `${prefix}-5-demo-later.png` });
console.log(errs.join("\n") || "no errors");
await browser.close();
