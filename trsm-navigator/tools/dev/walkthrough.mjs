import { chromium } from "@playwright/test";
const [,, base, prefix] = process.argv;
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
let n = 0;
const shot = async (name) => { await page.waitForTimeout(700); await page.screenshot({ path: `${prefix}-${String(n++).padStart(2, "0")}-${name}.png` }); };
await page.goto(base, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await shot("home");
await page.getByTestId("browse-washroom").tap();
await shot("washrooms");
await page.getByRole("button", { name: "Back" }).tap();
const box = page.locator('[data-testid="search"]:visible').first();
await box.tap(); await box.fill("harry");
await shot("search");
await page.locator('[data-testid="search-result"]:visible').first().tap();
await shot("place");
await page.getByTestId("directions").tap();
await shot("where-are-you");
await page.getByTestId("quick-L8:elevator-south-west").tap();
await shot("route");
await page.getByTestId("start-nav").tap();
await shot("nav-step1");
await page.getByTestId("next-step").tap();
await shot("nav-step2");
await page.getByTestId("next-step").tap();
await page.getByTestId("next-step").tap();
await shot("nav-step4");
// try to move the UI: drag on panel and pinch on top bar
const scroll0 = await page.evaluate(() => [window.scrollY, window.visualViewport?.scale ?? 1]);
const cdp = await page.context().newCDPSession(page);
await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: 195, y: 760 }] });
for (let i = 1; i < 8; i++) await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: 195, y: 760 - i * 30 }] });
await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: 150, y: 60, id: 1 }, { x: 240, y: 60, id: 2 }] });
for (let i = 1; i < 8; i++) await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: 150 - i * 10, y: 60, id: 1 }, { x: 240 + i * 10, y: 60, id: 2 }] });
await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
const scroll1 = await page.evaluate(() => [window.scrollY, window.visualViewport?.scale ?? 1, document.scrollingElement.scrollTop]);
console.log("scroll/scale before", scroll0, "after", scroll1);
await page.getByTestId("stop-nav").tap();
await page.getByTestId("demo-walk").tap();
await page.waitForTimeout(4000);
await shot("demo");
console.log(errs.join("\n") || "no page errors");
await browser.close();
